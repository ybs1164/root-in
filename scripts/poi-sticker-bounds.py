"""Measure where each map sticker is actually visible, after the app scales it.

python scripts/poi-sticker-bounds.py  ->  src/domain/poiStickerBounds.ts

The marker draws each PNG with object-fit: contain in a 48px square, then
scales it by POI_STICKER_SCALE[kind] about the centre (so every sticker shows
about the same area). Wide or tall art can then reach past the square: the
app needs the real outline to put the name under it and to keep stickers and
names of different places from touching (src/domain/poiScene.ts).
Alpha below 128 does not count, as in the scale table.
"""
import json
import re
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
BOX = 48


def read_scales():
    text = (ROOT / "src/domain/poiStickerScale.ts").read_text(encoding="utf-8")
    return {k: float(v) for k, v in re.findall(r'"([a-z_]+)":\s*([0-9.]+)', text)}


def bounds(path: Path, scale: float):
    image = Image.open(path).convert("RGBA")
    w, h = image.size
    box = image.getchannel("A").point(lambda a: 255 if a >= 128 else 0).getbbox()
    if not box:
        return None
    fit = BOX / max(w, h)
    ox, oy = (BOX - w * fit) / 2, (BOX - h * fit) / 2
    # Pixel edges in the 48px square, then scaled about its centre.
    edges = [ox + box[0] * fit, oy + box[1] * fit, ox + box[2] * fit, oy + box[3] * fit]
    left, top, right, bottom = [(e - BOX / 2) * scale for e in edges]
    # Round outwards to a tenth of a pixel.
    return [
        -(-left * 10 // 1) / 10 if left < 0 else (left * 10 // 1) / 10,
        -(-top * 10 // 1) / 10 if top < 0 else (top * 10 // 1) / 10,
        -(-right * 10 // 1) / 10,
        -(-bottom * 10 // 1) / 10,
    ]


def main():
    scales = read_scales()
    manifest = json.loads((ROOT / "public/poi-stickers/manifest.json").read_text(encoding="utf-8"))
    out = {}
    for kind in sorted(manifest["assets"]):
        b = bounds(ROOT / f"public/poi-stickers/{kind}.png", scales.get(kind, 1))
        if b:
            out[kind] = b
    lines = [
        "// Generated by scripts/poi-sticker-bounds.py; do not edit by hand.",
        "// Visible sticker outline (alpha >= 128) after object-fit: contain in the",
        "// 48px square and POI_STICKER_SCALE, in px from the square's centre:",
        "// [left, top, right, bottom], y down.",
        "export const POI_STICKER_BOUNDS: Record<string, readonly [number, number, number, number]> = {",
    ]
    lines += [f'  "{k}": [{", ".join(str(v) for v in b)}],' for k, b in out.items()]
    lines += ["};", ""]
    (ROOT / "src/domain/poiStickerBounds.ts").write_text("\n".join(lines), encoding="utf-8", newline="\n")
    worst = max(out.items(), key=lambda kv: max(abs(v) for v in kv[1]))
    print(f"{len(out)} stickers; widest reach {worst[0]} {worst[1]}")


if __name__ == "__main__":
    main()
